// Center reference for coordinate projection (UTM Zone 45N meters)
export const UTM_REF_X = 746000;
export const UTM_REF_Y = 2726000;
export const WORLD_SCALE = 0.006; // 1 unit in 3D world ~= 166 meters in real world

export function utmToWorld(utmX: number, utmY: number): [number, number] {
  const worldX = (utmX - UTM_REF_X) * WORLD_SCALE;
  const worldZ = -(utmY - UTM_REF_Y) * WORLD_SCALE; // Three.js Z is inverted North
  return [worldX, worldZ];
}

export function worldToUtm(worldX: number, worldZ: number): [number, number] {
  const utmX = worldX / WORLD_SCALE + UTM_REF_X;
  const utmY = -worldZ / WORLD_SCALE + UTM_REF_Y;
  return [utmX, utmY];
}

