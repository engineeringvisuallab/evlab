export type ProcessCategory = 
  | 'AERATION'
  | 'COAGULATION'
  | 'FLOCCULATION'
  | 'SEDIMENTATION'
  | 'FILTRATION'
  | 'DISINFECTION'
  | 'INTAKE'
  | 'PUMPING'
  | 'SLUDGE_THICKENING'
  | 'SLUDGE_DEWATERING'
  | 'CWR_STORAGE'
  | 'ELECTRICAL_SYSTEM';

export type LandRequirement = 'Very Low' | 'Low' | 'Medium' | 'High' | 'Very High';
export type EnergyRequirement = 'Very Low' | 'Low' | 'Medium' | 'High' | 'Very High';
export type ChemicalRequirement = 'None' | 'Low' | 'Medium' | 'High';
export type OperationalComplexity = 'Very Low' | 'Low' | 'Medium' | 'High' | 'Very High';
export type MaintenanceRequirement = 'Low' | 'Medium' | 'High';
export type AutomationRequirement = 'Basic' | 'Moderate' | 'Advanced' | 'Fully Automated';
export type SludgeGeneration = 'None' | 'Low' | 'Medium' | 'High';

export interface ApplicableWaterQuality {
  minTurbidity?: number;
  maxTurbidity?: number;
  minFeMn?: number;
  maxFeMn?: number;
  minTDS?: number;
  maxTDS?: number;
  maxAlgae?: number;
  maxTOC?: number;
  minUVT?: number;
}

export interface ApplicableFlowRange {
  minFlowMLD: number;
  maxFlowMLD: number;
}

