  shortDescription: string;
  detailedDescription: string;
  applicableWaterQuality: ApplicableWaterQuality;
  applicableFlowRange: ApplicableFlowRange;
  minimumFlow: number;
  maximumFlow: number;
  hydraulicRequirement: string;
  landRequirement: LandRequirement;
  landAreaFactor: number; // Multiplier relative to baseline (e.g. 1.0 = baseline, 0.35 = 65% land saved)
  energyRequirement: EnergyRequirement;
  chemicalRequirement: ChemicalRequirement;
  operationalComplexity: OperationalComplexity;
  maintenanceRequirement: MaintenanceRequirement;
  automationRequirement: AutomationRequirement;
  sludgeGeneration: SludgeGeneration;
  treatmentEfficiency: number; // 0 - 100
  reliability: number; // 0 - 100
  expandability: number; // 0 - 100
  constructability: number; // 0 - 100
